// ScriptOptions are the reviewed inputs of RenderScript.
type ScriptOptions struct {
	// Acknowledgements lists every destructive change ID exactly once.
	Acknowledgements []string
}

// RenderScript renders a reviewed artifact as one T-SQL script, unit by unit in
// the artifact's order. The script is a single batch, so an error in a unit
// ends the run and the units before it stay committed, as engine.Apply does.
//
// Each unit is one transaction (a unit with a non-transactional statement runs
// without one, under a session-owned lock) that takes the migration applock,
// then compares the unit's own changes with the catalog:
//   - every change still at its baseline: the unit's preconditions run, each a
//     THROW with the precondition's message when its query returns a row, then
//     its statements, each in its own batch (sp_executesql), so module DDL
//     starts a batch;
//   - every change already in its desired state: the unit is skipped, which is
//     what makes running the script again a no-op;
//   - anything else: the script THROWs that the unit matches neither state.
//
// A unit whose changes have no state to test (CREATE OR ALTER style module
// changes) runs every time, and is refused unless its statements are
// re-runnable. The guard covers the unit's own changes, not the dependents it
// drops and re-creates around them: those sit inside the same transaction. A
// dependent is dropped and created under the name recorded when the artifact
// was planned, so a script run on a database that names it differently fails
// and rolls its unit back. The statements are the artifact's, which are valid at
// the compatibility level the artifact was planned at; the script adds only
// THROW, sp_getapplock and sp_executesql, all available at level 100.
//
// The dialect "sqlserver" must be registered (import the dialect package), as
// the artifact is re-planned to prove it is the one its planner wrote.
func RenderScript(a engine.Artifact, options ScriptOptions) (string, error) {
	if a.Dialect != "sqlserver" {
		return "", fmt.Errorf("sqlserver: cannot render a %s artifact as a T-SQL script", a.Dialect)
	}
	if err := engine.Validate(a); err != nil {
		return "", err
	}
	if err := engine.ValidateAcknowledgements(a, options.Acknowledgements); err != nil {
		return "", err
	}
	var b strings.Builder
	if err := writeScriptHeader(&b, a, options.Acknowledgements); err != nil {
		return "", err
	}
	b.WriteString("DECLARE @options int = @@OPTIONS;\n" + SessionOptions + "\nDECLARE @lock int, @df sysname, @sql nvarchar(max);\n")
	snaps := snapshots{current: a.Baseline, desired: a.Desired}
	for i, u := range a.Units {
		block, err := renderUnit(a, snaps, u, i+1)
		if err != nil {
			return "", err
		}
		b.WriteString(block)
	}
	b.WriteString(restoreSessionOptions)
	if batchSeparator.MatchString(b.String()) {
		return "", fmt.Errorf("sqlserver: migration %s: a statement contains a GO line, which would split the script into batches", a.Hash)
	}
	return b.String(), nil
}

func writeScriptHeader(b *strings.Builder, a engine.Artifact, acknowledgements []string) error {
	schemas, err := json.Marshal(a.Scope.Schemas)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "-- sqlglot SQL Server migration artifact %s\n", a.Hash)
	b.WriteString("-- Generated by sqlglot-go RenderScript. Nothing verifies the hash when the script runs: a hand-edited script is no longer the reviewed artifact, so re-render it instead of editing it.\n")
	b.WriteString("-- One batch, one transaction per unit: an error ends the script and keeps the units before it; run it again to resume after them. Session options are restored after the last unit, except QUOTED_IDENTIFIER, which stays ON; a failed run leaves them as this script sets them.\n")
	fmt.Fprintf(b, "-- Planned against capabilities %s\n", a.Capabilities.Fingerprint)
	fmt.Fprintf(b, "-- Scope: %s, schemas: %s\n", a.Scope.Mode, schemas)
	changes := make([]string, len(a.Changes))
	for i, c := range a.Changes {
		changes[i] = c.ID
		if c.Cause != "" {
			changes[i] += " (forced by " + c.Cause + ")"
		}
	}
	writeHeaderList(b, "Changes", changes)
	acknowledged := slices.Clone(acknowledgements)
	slices.Sort(acknowledged)
	writeHeaderList(b, "Acknowledged destructive changes", acknowledged)
	return nil
}

// renderUnit renders unit n as one transaction under the migration applock.
func renderUnit(a engine.Artifact, snaps snapshots, u engine.Unit, n int) (string, error) {
	flag := "@u" + strconv.Itoa(n)
	state, err := unitStateGuard(a, snaps, u, flag)
	if err != nil {
		return "", err
	}
	owner, begin, end := "Session", "", fmt.Sprintf("EXEC sys.sp_releaseapplock @Resource = %s, @LockOwner = 'Session';\n", literal(LockResource))
	if u.Transactional {
		owner, begin, end = "Transaction", "BEGIN TRANSACTION;\n", "COMMIT TRANSACTION;\n"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- unit %s: %s\nDECLARE %s bit = 0;\n%s", u.ID, strings.Join(u.Changes, ", "), flag, begin)
	fmt.Fprintf(&b, "EXEC @lock = sys.sp_getapplock @Resource = %s, @LockMode = 'Exclusive', @LockOwner = '%s', @LockTimeout = %d;\n", literal(LockResource), owner, scriptLockTimeoutMillis)
	fmt.Fprintf(&b, "IF @lock < 0 THROW 50000, %s, 1;\n", literal(fmt.Sprintf("migration %s unit %s: sp_getapplock on %s failed", a.Hash, u.ID, LockResource)))
	b.WriteString(state)
	for _, p := range u.Preconditions {
		fmt.Fprintf(&b, "-- precondition %s\nIF %s = 1 AND EXISTS (%s) THROW 50000, %s, 1;\n", p.ID, flag, p.SQL, literal(p.Message))
	}
	statements, err := unitStatements(a, snaps, u, flag)
	if err != nil {
		return "", err
	}
	b.WriteString(statements)
	b.WriteString(end)
	return b.String(), nil
}

// ownUnitChanges are the unit's changes the diff names; the forced rebuilds
// ride inside the unit and have no state of their own.
func ownUnitChanges(a engine.Artifact, u engine.Unit) []migrate.Change {
	var own []migrate.Change
	for _, c := range a.Changes {
		if c.Action != "rebuild" && slices.Contains(u.Changes, c.ID) {
			own = append(own, c)
		}
	}
	return own
}

// unitStateGuard sets flag to 1 when every guarded change of the unit is at its
// baseline, leaves it 0 when every one is in its desired state, and throws when
// they disagree or any is in neither.
func unitStateGuard(a engine.Artifact, snaps snapshots, u engine.Unit, flag string) (string, error) {
	var pending, applied []string
	var unguarded []migrate.Change
	for _, c := range ownUnitChanges(a, u) {
		guard, err := changeGuard(snaps, c)
		if err != nil {
			return "", err
		}
		if guard.apply == "" {
			unguarded = append(unguarded, c)
			continue
		}
		pending = append(pending, guard.apply)
		if guard.applied == "" {
			guard.applied = "NOT " + guard.apply
		}
		applied = append(applied, guard.applied)
	}
	if len(pending) == 0 {
		return "SET " + flag + " = 1;\n", requireRerunnable(u, unguarded)
	}
	message := fmt.Sprintf("migration %s: unit %s matches neither its baseline nor its desired state", a.Hash, u.ID)
	return "IF " + strings.Join(pending, " AND ") + " SET " + flag + " = 1;\n" +
		"ELSE IF NOT (" + strings.Join(applied, " AND ") + ") THROW 50000, " + literal(message) + ", 1;\n", nil
}

// requireRerunnable refuses a unit that always runs unless every statement of
// its changes converges when run again.
func requireRerunnable(u engine.Unit, changes []migrate.Change) error {
	for _, c := range changes {
		var steps []step
		for _, op := range u.Ops {
			for _, s := range op.Statements {
				steps = append(steps, step{change: c, sql: s.SQL})
			}
		}
		if err := requireIdempotent(steps, c); err != nil {
			return fmt.Errorf("sqlserver: unit %s: %w", u.ID, err)
		}
	}
	return nil
}

// unitStatements runs each statement under the unit's flag, a statement that
// drops a column's baseline default under the name the database gives it.
func unitStatements(a engine.Artifact, snaps snapshots, u engine.Unit, flag string) (string, error) {
	byID := make(map[string]migrate.Change, len(a.Changes))
	for _, c := range a.Changes {
		byID[c.ID] = c
	}
	var b strings.Builder
	for _, op := range u.Ops {
		for _, s := range op.Statements {
			statement, err := stepStatement(snaps, step{change: byID[op.Change], sql: s.SQL}, flag)
			if err != nil {
				return "", err
			}
			b.WriteString(statement)
		}
	}
	return b.String(), nil
}
